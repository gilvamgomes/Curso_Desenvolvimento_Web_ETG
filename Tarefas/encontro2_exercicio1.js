/* 
5.1.Exercício 1: Conversor de Temperatura
Crie um algoritmo que leia uma temperatura em graus Celsius e a converta para Fahrenheit. A fórmula de conversão é: F = (C * 9/5) + 32. Este exercício demonstra o uso de variáveis, operações aritméticas e a aplicação de uma fórmula matemática em programação.
*/

//Declaração do valor do Celsius a ser convertido
let celsius = 25;

//Fórmula do Fahrenheit 
let fahrenheit = (celsius * 9/5) + 32;

//Exibe o resultado
console.log("A temperatura em Fahrenheit é:", fahrenheit);

